/** A BCP 47 tag from Zotero's free-text language field, or undefined. */
export function languageTag(raw: string | undefined): string | undefined {
  if (!raw) return undefined;
  const v = raw.trim();
  if (/^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$/.test(v)) return v;
  const m = /^([a-z]{2,3})[_-]([A-Za-z]{2})$/i.exec(v);
  if (m) return `${(m[1] ?? "").toLowerCase()}-${(m[2] ?? "").toUpperCase()}`;
  return LANGUAGE_NAMES[v.toLowerCase()];
}
